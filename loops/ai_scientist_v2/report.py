"""
The stage outputs: the idea's files, literature review, experiments, analysis and
report, with citations found through the literature server.

Citation and report prompts are adapted from AI Scientist-v2's
`ai_scientist/perform_icbinb_writeup.py` (`get_citation_addition`,
`writeup_system_message_template`); see LICENSE. Reports are markdown, and every
reference list is built by code from the papers' metadata, so it can't be made up.
"""

import json
import shutil
from pathlib import Path

from ai_scientist_v2.literature import search_papers
from ai_scientist_v2.llm import call_tool, query
from ai_scientist_v2.nodes import Node, emit, summarise_journal

# The licence requires machine-generated outputs to say so prominently
_DISCLOSURE = (
    "## Disclosure\n\n"
    "This document was generated by an AI system, a reimplementation of The AI "
    "Scientist-v2 (Sakana AI), and has not been checked by a person."
)

_FIND_TOOL = {
    "type": "function",
    "function": {
        "name": "find_citation",
        "description": "Name the most important citation still missing, or stop.",
        "parameters": {
            "type": "object",
            "properties": {
                "done": {
                    "type": "boolean",
                    "description": "true if no more citations are needed.",
                },
                "description": {
                    "type": "string",
                    "description": "The purpose of the citation, and what you are "
                    "looking for.",
                },
                "query": {
                    "type": "string",
                    "description": "The search query to find the paper, e.g. "
                    "'attention is all you need'.",
                },
            },
            "required": ["done"],
        },
    },
}

_SELECT_TOOL = {
    "type": "function",
    "function": {
        "name": "select_citations",
        "description": "Select the search results to cite, possibly none.",
        "parameters": {
            "type": "object",
            "properties": {
                "indices": {
                    "type": "array",
                    "items": {"type": "integer"},
                    "description": "Indices of the selected papers, e.g. [0, 1].",
                },
                "description": {
                    "type": "string",
                    "description": "A brief description of the selected work(s), "
                    "their relevance, and where in the report to cite them.",
                },
            },
            "required": ["indices", "description"],
        },
    },
}

_CITATION_SYSTEM = (
    "You are an ambitious researcher who has completed your experiments and is now "
    "collecting citations to related papers, to be used in the report.\n\n"
    "Reasons to reference papers include:\n"
    "1. Summarising research: when summarising the existing literature.\n"
    "2. Using specific concepts: when discussing specific theories or concepts.\n"
    "3. Datasets, models and methods: cite their creators.\n"
    "4. Comparing findings: when comparing or contrasting different findings.\n"
    "5. Highlighting research gaps: when pointing out gaps your study addresses.\n"
    "6. Using established methods: cite the creators of methods you use.\n"
    "7. Supporting arguments: sources that back up your conclusions.\n"
    "8. Suggesting future research: studies related to future directions.\n\n"
    "Collect citations for all of these categories. Aim for a broad range of "
    "relevant papers, not just the most popular ones. You have {rounds} rounds, but "
    "do not need to use them all. DO NOT ADD A CITATION THAT ALREADY EXISTS!"
)

_REPORT_SYSTEM = (
    "You are an ambitious researcher writing up your project as a report. You must "
    "accurately represent the results of the experiments: negative, unexpected or "
    "inconclusive findings are valid contributions. Write markdown with these "
    "sections:\n\n"
    "- **Title**: catchy and informative.\n"
    "- **Abstract**: one paragraph summarising the question, method and findings.\n"
    "- **Introduction**: the problem, why it matters, and the contributions.\n"
    "- **Related Work**: relevant papers, compared and contrasted with this work. "
    "It should have several citations.\n"
    "- **Method**: what was done, in enough detail to repeat it.\n"
    "- **Results**: what the experiments found.\n"
    "- **Ablations**: which parts of the approach mattered.\n"
    "- **Limitations**: how far the results can be trusted.\n"
    "- **Conclusion**: the main lessons, and next steps.\n\n"
    "Don't invent results or citations. Don't add a references section; it is "
    "added for you."
)


def save_output(results: Path, stage: str, text: str) -> None:
    """Write a stage's markdown file, ending with the disclosure; emit its event."""
    path = results / f"{stage}.md"
    path.write_text(f"{text.strip()}\n\n{_DISCLOSURE}\n")
    emit("output", stage=stage, path=str(path))


def research_questions(idea: dict) -> str:
    """The research_questions output, from the idea's fields."""
    return (
        f"# {idea['Title']}\n\n"
        f"## Hypothesis\n\n{idea['Short Hypothesis']}\n\n"
        f"## Abstract\n\n{idea['Abstract']}"
    )


def research_design(idea: dict) -> str:
    """The research_design output, from the idea's fields."""
    metric = idea["Metric"]
    direction = "higher" if metric["higher_is_better"] else "lower"
    return (
        f"# Research design: {idea['Title']}\n\n"
        f"## Experiments\n\n{idea['Experiments']}\n\n"
        f"## Metric\n\n`{metric['name']}`, where {direction} is better.\n\n"
        f"## Risk factors and limitations\n\n{idea['Risk Factors and Limitations']}"
    )


def write_lit_review(prompt: str, idea: dict, papers: list[dict], model: str) -> str:
    """
    Write a literature review of the papers the idea relies on.

    Args:
        prompt: The task prompt the loop was started with.
        idea: The research idea, from `generate_idea`.
        papers: The idea's papers, from `generate_idea`.
        model: Model name as configured in the LiteLLM gateway.

    Returns:
        The review in markdown, with its reference list.
    """
    listing = "\n\n".join(
        f"[{i}] {p['title']} ({p['year']})\n{p.get('abstract') or 'No abstract.'}"
        for i, p in enumerate(papers, 1)
    )
    text = _ask(
        model,
        "You are an experienced researcher writing a literature review.",
        f"Task:\n{prompt}\n\n"
        f"Research idea: {idea['Title']}\n{idea['Short Hypothesis']}\n\n"
        f"Related work, as summarised in the idea:\n{idea['Related Work']}\n\n"
        f"Papers:\n{listing}\n\n"
        "Write a short markdown literature review of these papers. Group them by "
        "theme, say how each relates to the idea, and name the gap the idea "
        "addresses. Cite papers only by their number, e.g. [3]. Don't add a "
        "references section; it is added for you.",
    )
    return f"{text}\n\n{_references(papers)}"


def write_experiments(bests: dict[str, Node], tree: Path, out: Path) -> None:
    """
    Copy the main best node's script, metrics and plots, and the journal.

    Args:
        bests: Each finished search stage's best node, from `run_stages`.
        tree: The search's folder, with the nodes' folders and `journal.json`.
        out: The experiments output folder, created if missing.
    """
    out.mkdir(parents=True, exist_ok=True)
    best = _main_best(bests)
    files = [*tree.glob("*.json")]
    if best:
        node_dir = tree / best.id
        files += [node_dir / "runfile.py", node_dir / "metrics.json"]
        files += sorted(node_dir.glob("*.png"))
    for path in files:
        shutil.copy(path, out)
    emit("output", stage="experiments", path=str(out))


def write_analysis(
    idea: dict, bests: dict[str, Node], nodes: list[Node], model: str
) -> str:
    """
    Analyse what the search found about the hypothesis.

    Args:
        idea: The research idea, from `generate_idea`.
        bests: Each finished search stage's best node, from `run_stages`.
        nodes: Every node, from `run_stages`.
        model: Model name as configured in the LiteLLM gateway.

    Returns:
        The analysis, in markdown.
    """
    metric = idea["Metric"]
    direction = "higher" if metric["higher_is_better"] else "lower"
    base = bests.get("creative_research")
    ablations = "\n".join(
        f"- {n.plan.splitlines()[0]}: {metric['name']} = {n.metric}"
        for n in nodes
        if n.op == "ablate" and not n.is_bug
    )
    return _ask(
        model,
        "You are an experienced researcher analysing your experiments' results.",
        f"Research idea:\n{json.dumps(idea, indent=2)}\n\n"
        f"The metric is `{metric['name']}`, and {direction} is better.\n\n"
        f"Best implementation of each search stage:\n{_bests_text(bests)}\n\n"
        f"Ablations, against {metric['name']} = {base.metric if base else None} "
        f"before ablating:\n{ablations or 'None ran successfully.'}\n\n"
        f"Recent attempts:\n{summarise_journal(nodes)}\n\n"
        "Write a markdown analysis of what the results show about the hypothesis, "
        "which ablated parts mattered, and how far the results can be trusted. "
        "Quote numbers only from the metrics given.",
    )


def gather_citations(
    idea: dict, analysis: str, papers: list[dict], rounds: int, model: str
) -> list[dict]:
    """
    Find papers for the report to cite, one search per round.

    Args:
        idea: The research idea, from `generate_idea`.
        analysis: From `write_analysis`.
        papers: The idea's papers, which start the list.
        rounds: The most rounds of searching.
        model: Model name as configured in the LiteLLM gateway.

    Returns:
        The idea's papers and the selected ones, each with a "reason" for citing it.
    """
    cited = [{**p, "reason": "Related work the idea builds on."} for p in papers]
    system = {"role": "system", "content": _CITATION_SYSTEM.format(rounds=rounds)}
    for round_num in range(1, rounds + 1):
        context = (
            f"Round {round_num}/{rounds}.\n\n"
            f"Your idea:\n{json.dumps(idea, indent=2)}\n\n"
            f"Your analysis of the results:\n{analysis}\n\n"
            f"Your current citations:\n{_citations_text(cited)}"
        )
        ask = (
            f"{context}\n\nIdentify the most important citation you still need to "
            "add, and the query to find it, or say you are done."
        )
        find = call_tool(model, [system, _user(ask)], _FIND_TOOL)
        if find["done"]:
            break
        found = search_papers(find["query"])
        listing = "\n".join(
            f"{i}: {p['title']} ({p['year']})" for i, p in enumerate(found)
        )
        ask = (
            f"{context}\n\nYou are looking for: {find['description']}\n\n"
            f"Search found:\n{listing}\n\nSelect the papers that best fit, if any. "
            "Don't select papers that are already cited."
        )
        select = call_tool(model, [system, _user(ask)], _SELECT_TOOL)
        known = {p["paper_id"] for p in cited}
        cited += [
            {**found[i], "reason": select["description"]}
            for i in dict.fromkeys(select["indices"])
            if 0 <= i < len(found) and found[i]["paper_id"] not in known
        ]
    emit("citations", count=len(cited))
    return cited


def write_report(
    idea: dict, analysis: str, bests: dict[str, Node], cited: list[dict], model: str
) -> str:
    """
    Write the report, citing the gathered papers by number.

    Args:
        idea: The research idea, from `generate_idea`.
        analysis: From `write_analysis`.
        bests: Each finished search stage's best node, from `run_stages`.
        cited: From `gather_citations`.
        model: Model name as configured in the LiteLLM gateway.

    Returns:
        The report in markdown, with its reference list.
    """
    text = _ask(
        model,
        _REPORT_SYSTEM,
        f"Write up the following idea:\n{json.dumps(idea, indent=2)}\n\n"
        f"Your analysis of the results:\n{analysis}\n\n"
        f"Best implementation of each search stage:\n{_bests_text(bests)}\n\n"
        f"Papers you can cite:\n{_citations_text(cited, numbered=True)}\n\n"
        "Quote numbers only from the metrics given, and cite papers only by their "
        "number, e.g. [3].",
    )
    return f"{text}\n\n{_references(cited)}"


def _user(text: str) -> dict:
    """A user message."""
    return {"role": "user", "content": text}


def _ask(model: str, system: str, prompt: str) -> str:
    """Ask the model for a text reply."""
    return query(model, [{"role": "system", "content": system}, _user(prompt)]).content


def _main_best(bests: dict[str, Node]) -> Node | None:
    """The best node of the last search stage before the ablations."""
    main = [n for stage, n in bests.items() if stage != "ablation_studies"]
    return main[-1] if main else None


def _bests_text(bests: dict[str, Node]) -> str:
    """Each search stage's best node: its plan, metric and review."""
    return (
        "\n\n".join(
            f"{stage} (node {n.id}):\nPlan: {n.plan}\nMetric: {n.metric}\n"
            f"Review: {n.summary}\nPlot feedback: {n.plot_feedback or 'none'}"
            for stage, n in bests.items()
        )
        or "No implementation worked."
    )


def _citations_text(cited: list[dict], numbered: bool = False) -> str:
    """List cited papers with why each is cited; numbered from 1 for the report."""
    return (
        "\n".join(
            f"{f'[{i}]' if numbered else '-'} {p['title']} ({p['year']}): {p['reason']}"
            for i, p in enumerate(cited, 1)
        )
        or "None yet."
    )


def _references(papers: list[dict]) -> str:
    """A numbered reference list, from the papers' metadata."""
    entries = "\n".join(
        f"{i}. {', '.join(p['authors'])} ({p['year']}). {p['title']}. "
        f"{p.get('venue') or ''} {p.get('url') or ''}".rstrip()
        for i, p in enumerate(papers, 1)
    )
    return f"## References\n\n{entries or 'None.'}"
